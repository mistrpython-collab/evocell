// ===== FUNGSI HELPER =====

export function getLang(key) {
    const currentLang = getCurrentLang();
    return translations[currentLang][key] || key;
}

export function getCurrentLang() {
    return localStorage.getItem('evocell_lang') || 'id';
}

export function toggleLanguage() {
    const currentLang = getCurrentLang();
    const newLang = currentLang === 'id' ? 'en' : 'id';
    localStorage.setItem('evocell_lang', newLang);
    return newLang;
}

export function setLanguage(lang) {
    if (lang === 'id' || lang === 'en') {
        localStorage.setItem('evocell_lang', lang);
        return lang;
    }
    return getCurrentLang();
}

// ===== TOGGLE SWITCH BAHASA =====
// Teks EN & ID SELALU PUTIH TERANG
// Knob HIJAU sebagai indikator bahasa aktif (kiri=EN, kanan=ID)

export function createLanguageSwitch(scene, x, y) {
    const currentLang = getCurrentLang();
    
    // Ukuran switch
    const switchWidth = 120;
    const switchHeight = 36;
    const knobRadius = 14;
    const knobOffset = switchWidth / 2 - knobRadius - 8;
    
    // Container untuk seluruh switch
    const container = scene.add.container(x, y);
    container.setDepth(1000);
    
    // 1. Background track
    const track = scene.add.graphics();
    track.fillStyle(0x2a2a2a, 1);
    track.fillRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
    track.lineStyle(2, 0x555555, 1);
    track.strokeRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
    container.add(track);
    
    // 2. Label EN (kiri) - SELALU PUTIH
    const enLabel = scene.add.text(-switchWidth/2 + 22, 0, 'EN', {
        font: 'bold 14px Arial',
        fill: '#ffffff',
        stroke: '#000000',
        strokeThickness: 2
    }).setOrigin(0.5);
    container.add(enLabel);
    
    // 3. Label ID (kanan) - SELALU PUTIH
    const idLabel = scene.add.text(switchWidth/2 - 22, 0, 'ID', {
        font: 'bold 14px Arial',
        fill: '#ffffff',
        stroke: '#000000',
        strokeThickness: 2
    }).setOrigin(0.5);
    container.add(idLabel);
    
    // 4. Knob - HIJAU sebagai indikator aktif
    // ID aktif = knob di KANAN, EN aktif = knob di KIRI
    const knobX = currentLang === 'id' ? knobOffset : -knobOffset;
    const knob = scene.add.graphics();
    knob.fillStyle(0x00ff00, 1);
    knob.fillCircle(knobX, 0, knobRadius);
    knob.lineStyle(2, 0x00cc00, 1);
    knob.strokeCircle(knobX, 0, knobRadius);
    container.add(knob);
    
    // 5. HitArea
    const hitArea = new Phaser.Geom.Rectangle(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight);
    container.setInteractive(hitArea, Phaser.Geom.Rectangle.Contains);
    
    // 6. Event klik - Toggle bahasa
    container.on('pointerdown', () => {
        const newLang = toggleLanguage();
        const newKnobX = newLang === 'id' ? knobOffset : -knobOffset;
        
        // Animasi geser knob
        scene.tweens.add({
            targets: knob,
            x: newKnobX,
            duration: 300,
            ease: 'Power2'
        });
        
        // Teks EN & ID TETAP PUTIH (tidak perlu diubah)
        // Hanya knob yang bergeser sebagai indikator
        
        // Restart scene setelah animasi
        scene.time.delayedCall(350, () => {
            scene.scene.restart();
        });
    });
    
    // 7. Hover effect
    container.on('pointerover', () => {
        track.clear();
        track.fillStyle(0x3a3a3a, 1);
        track.fillRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
        track.lineStyle(2, 0x00ff00, 1);
        track.strokeRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
    });
    
    container.on('pointerout', () => {
        track.clear();
        track.fillStyle(0x2a2a2a, 1);
        track.fillRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
        track.lineStyle(2, 0x555555, 1);
        track.strokeRoundedRect(-switchWidth/2, -switchHeight/2, switchWidth, switchHeight, 18);
    });
    
    return container;
}